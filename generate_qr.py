"""Generate self-hosted SVG QR codes and links.js from links.json."""

from __future__ import annotations

import json
from pathlib import Path
from urllib.parse import urlparse

import qrcode
from qrcode.image.svg import SvgPathImage


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "links.json"
OUTPUT = ROOT / "links.js"
QR_DIR = ROOT / "assets" / "qr"


def main() -> None:
    links = json.loads(SOURCE.read_text(encoding="utf-8"))
    if not isinstance(links, list):
        raise ValueError("links.json must contain a list of links")

    QR_DIR.mkdir(parents=True, exist_ok=True)
    for old_file in QR_DIR.glob("*.svg"):
        old_file.unlink()

    generated = []
    for index, item in enumerate(links, start=1):
        if not isinstance(item, dict):
            raise ValueError(f"Link {index} must be an object")
        url = str(item.get("url", "")).strip()
        parsed = urlparse(url)
        if parsed.scheme not in {"https", "http"} or not parsed.netloc:
            raise ValueError(f"Link {index} needs a valid public http(s) URL")
        if not str(item.get("name", "")).strip():
            raise ValueError(f"Link {index} needs a name")

        qr_name = f"qr-{index:02d}.svg"
        qr = qrcode.QRCode(border=4, box_size=8, error_correction=qrcode.constants.ERROR_CORRECT_M)
        qr.add_data(url)
        qr.make(fit=True)
        qr.make_image(
            image_factory=SvgPathImage,
            fill_color="#2b3439",
            back_color="#fffdf9",
        ).save(QR_DIR / qr_name)
        generated.append({**item, "qr": f"assets/qr/{qr_name}"})

    OUTPUT.write_text(
        "// Generated by generate_qr.py from links.json.\n"
        "window.HYPERTEAM_LINKS = "
        + json.dumps(generated, ensure_ascii=False, indent=2)
        + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
